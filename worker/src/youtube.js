// Extrae subtitulos publicos de YouTube.
//
// Estrategia:
//   1. Si TRANSCRIPT_SERVICE_URL esta configurado, delega en el
//      microservicio Python (youtube-transcript-api). Es el camino
//      fiable hoy: la libreria resuelve PoToken y demas bloqueos.
//   2. Si no, intenta Innertube ANDROID/IOS/WEB como fallback.

class TranscriptError extends Error {
  constructor(status, message) {
    super(message);
    this.status = status;
  }
}

async function fetchWithTimeout(url, options, timeoutMs) {
  const controller = new AbortController();
  const timeoutId = setTimeout(() => controller.abort(), timeoutMs);
  try {
    return await fetch(url, { ...options, signal: controller.signal });
  } finally {
    clearTimeout(timeoutId);
  }
}

async function viaTranscriptService(videoId, preferredLang, serviceUrl) {
  const url = new URL(`${serviceUrl.replace(/\/$/, "")}/transcript`);
  url.searchParams.set("video_id", videoId);
  if (preferredLang) url.searchParams.set("lang", preferredLang);

  console.log("[viaTranscriptService] GET", url.toString());
  const res = await fetchWithTimeout(url.toString(), { method: "GET" }, 20000);
  const text = await res.text();

  if (!res.ok) {
    let detail = text;
    try {
      const parsed = JSON.parse(text);
      detail = parsed.detail || parsed.error || text;
    } catch {}
    console.log("[viaTranscriptService] HTTP", res.status, detail);
    throw new TranscriptError(
      res.status,
      detail || "Error en el servicio de transcripts."
    );
  }

  let data;
  try {
    data = JSON.parse(text);
  } catch {
    throw new TranscriptError(
      502,
      "El servicio de transcripts devolvio JSON invalido."
    );
  }

  return {
    platform: "youtube",
    videoId: data.videoId || videoId,
    title: data.title || null,
    author: data.author || null,
    thumbnails: Array.isArray(data.thumbnails) ? data.thumbnails : [],
    language: data.language || null,
    languageName: data.languageName || data.language || null,
    isAutoGenerated: Boolean(data.isAutoGenerated),
    source: data.isAutoGenerated ? "speech-to-text" : "native",
    segmentCount:
      data.segmentCount ?? (data.transcript ? data.transcript.length : 0),
    transcript: data.transcript || [],
    fullText: data.fullText || "",
  };
}

